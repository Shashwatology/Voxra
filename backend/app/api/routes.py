"""
Guarded Enquiry Service - API Routes
Defines all operational endpoints: /ask, /health, /faq, /metrics, /evaluation, /handoffs.
"""

from datetime import datetime, timezone
import json
from pathlib import Path
from typing import List, Optional
from fastapi import APIRouter, Header, HTTPException, status
from backend.app.core.config import settings
from backend.app.core.logging import logger
from backend.app.models.request import AskRequest, HandoffResolveRequest
from backend.app.models.response import (
    AskResponse,
    FaqItem,
    HandoffRecord,
    HealthResponse,
    MetricsSummaryResponse,
)
from backend.app.services.answer_service import answer_service
from backend.app.services.audit_service import audit_service
from backend.app.services.faq_service import faq_service
from backend.app.services.gemini_service import gemini_service

router = APIRouter()

@router.post(
    "/ask",
    response_model=AskResponse,
    summary="Submit parent or student enquiry",
    description="Processes an enquiry through input guardrails, retrieval, and canonical FAQ grounding."
)
async def ask_question(request: AskRequest) -> AskResponse:
    """Handles an enquiry with absolute factual grounding and controlled escalation."""
    return await answer_service.process_question(request)

@router.get(
    "/health",
    response_model=HealthResponse,
    summary="System health check",
    description="Returns operational state, AI mode, and knowledge base metadata."
)
async def health_check() -> HealthResponse:
    """Verifies service readiness and configuration."""
    return HealthResponse(
        status="healthy",
        ai_mode=settings.AI_MODE,
        gemini_configured=gemini_service.is_configured,
        model_name=settings.GEMINI_MODEL,
        faq_count=len(faq_service.get_all_faqs()),
        faq_version=faq_service.version,
        timestamp=datetime.now(timezone.utc).isoformat()
    )

@router.get(
    "/faq",
    response_model=List[FaqItem],
    summary="Retrieve canonical FAQ list",
    description="Returns all 15 immutable approved FAQ entries with category tags and metadata."
)
async def get_faqs() -> List[FaqItem]:
    """Returns the immutable approved FAQ knowledge base."""
    return faq_service.get_all_faqs()

@router.get(
    "/metrics/summary",
    response_model=MetricsSummaryResponse,
    summary="Operational metrics summary",
    description="Aggregated real runtime telemetry: answer coverage, latency, category counts."
)
async def get_metrics() -> MetricsSummaryResponse:
    """Returns live operational telemetry recorded during requests."""
    return audit_service.get_metrics_summary()

@router.get(
    "/evaluation/results",
    summary="Benchmark evaluation results",
    description="Loads the reproducible results generated by scripts/evaluate.py."
)
async def get_evaluation_results():
    """Retrieves the latest reproducible evaluation benchmark execution data."""
    if not settings.EVALUATION_RESULTS_PATH.exists():
        return {
            "status": "not_executed",
            "message": "Evaluation script has not yet been executed. Run: python scripts/evaluate.py",
            "summary": None,
            "results": []
        }
    try:
        with open(settings.EVALUATION_RESULTS_PATH, "r", encoding="utf-8") as f:
            results_data = json.load(f)
        summary_data = None
        if settings.EVALUATION_SUMMARY_PATH.exists():
            with open(settings.EVALUATION_SUMMARY_PATH, "r", encoding="utf-8") as f:
                summary_data = json.load(f)
        return {
            "status": "available",
            "summary": summary_data,
            "results": results_data
        }
    except Exception as e:
        logger.error(f"Failed to read evaluation artifacts: {e}")
        raise HTTPException(status_code=500, detail="Error reading evaluation artifacts.")

@router.get(
    "/handoffs",
    response_model=List[HandoffRecord],
    summary="Escalation handoff review queue",
    description="Returns escalated queries for admissions staff review."
)
async def get_handoffs(x_admin_key: Optional[str] = Header(None)) -> List[HandoffRecord]:
    """Returns the human review queue."""
    # In development, allow access; in production, verify header
    if settings.ENVIRONMENT == "production" and x_admin_key != settings.ADMIN_API_KEY:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or missing admin authentication key."
        )
    return audit_service.get_handoffs()

@router.post(
    "/handoffs/{request_id}/resolve",
    response_model=HandoffRecord,
    summary="Resolve an escalated handoff item",
    description="Updates review status and notes by admissions personnel."
)
async def resolve_handoff(
    request_id: str,
    payload: HandoffResolveRequest,
    x_admin_key: Optional[str] = Header(None)
) -> HandoffRecord:
    """Updates the status and reviewer notes on an escalation record."""
    if settings.ENVIRONMENT == "production" and x_admin_key != settings.ADMIN_API_KEY:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or missing admin authentication key."
        )
    record = audit_service.resolve_handoff(
        request_id=request_id,
        status=payload.resolution_status,
        reviewer_notes=payload.reviewer_notes
    )
    if not record:
        raise HTTPException(status_code=404, detail="Handoff record not found.")
    return record
